export type TranslationKey = keyof typeof en;
type TranslationMap = Record<TranslationKey, string>;
export const translations: Record<Lang, TranslationMap> = { en, es };

export type TranslationVars = Record<string, string | number>;

/**
 * Look up a string, filling `{name}` placeholders from `vars`.
 *
 * Interpolating here rather than concatenating in the caller is what lets a
 * translation reorder the sentence around its values, which Spanish often has
 * to do. A placeholder with no matching variable is left alone, so a typo shows
 * up in the interface instead of silently blanking the text.
 */
export function useT(): (key: TranslationKey, vars?: TranslationVars) => string {
  const lang = useSettingsStore((s) => s.lang);
  return (key: TranslationKey, vars?: TranslationVars) => {
    const text = translations[lang][key] ?? en[key] ?? key;
    if (!vars) return text;
    return text.replace(/\{(\w+)\}/g, (whole, name) =>
      name in vars ? String(vars[name]) : whole
    );
  };
}
